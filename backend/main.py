@app.post("/api/run")
async def run_prompt(request: RunRequest):
    """
    Executes a prompt against the requested LLM.
    Enforces JSON schema if provided.
    """
    messages = [{"role": "user", "content": request.prompt}]
    
    try:
        # Native async call is safe here because there is no DB interaction
        result = await router.get_completion(
            model_key=request.model,
            messages=messages,
            json_schema=request.json_schema
        )
        if "error" in result:
            raise HTTPException(status_code=500, detail=result["error"])
        
        return result
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/evaluate")
async def evaluate_prompt(request: EvaluateRequest):
    """
    Evaluates a prompt and its output using the 9-Axis PEEM Protocol.
    """
    user_content = f"### ORIGINAL PROMPT:\n{request.prompt}\n\n### LLM OUTPUT:\n{request.output}\n\nEvaluate this based on the PEEM protocol."
    
    messages = [
        {"role": "system", "content": PEEM_SYSTEM_PROMPT},
        {"role": "user", "content": user_content}
    ]
    
    try:
        # Native async call is safe here because there is no DB interaction
        result = await router.get_completion(
            model_key=request.judge_model,
            messages=messages,
            json_schema=PEEM_SCHEMA
        )
        if "error" in result:
            raise HTTPException(status_code=500, detail=result["error"])
        
        # Parse the JSON response
        try:
            evaluation_data = json.loads(result["content"])
        except json.JSONDecodeError:
            raise HTTPException(status_code=500, detail="Judge LLM failed to return valid JSON.")
            
        return {
            "evaluation": evaluation_data,
            "usage": result.get("usage"),
            "model": result.get("model")
        }
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/save")
async def save_run(request: SaveRequest, db: Session = Depends(get_db)):
    """
    Saves a prompt version and its evaluation score to the database.
    """
    try:
        # Create a default user if none exists
        user = db.query(models.User).filter(models.User.username == "default_user").first()
        if not user:
            user = models.User(username="default_user")
            db.add(user)
            db.commit()
            db.refresh(user)

        # Create or find prompt parent
        prompt = db.query(models.Prompt).filter(models.Prompt.title == request.title, models.Prompt.owner_id == user.id).first()
        if not prompt:
            prompt = models.Prompt(title=request.title, owner_id=user.id)
            db.add(prompt)
            db.commit()
            db.refresh(prompt)
            
        # Save the prompt version
        version = models.PromptVersion(
            prompt_id=prompt.id,
            content=request.prompt_content,
            model_used=request.model_used
        )
        db.add(version)
        db.commit()
        db.refresh(version)

        # Save evaluation if provided
        if request.evaluation_scores:
            evaluation = models.Evaluation(
                prompt_version_id=version.id,
                scores=request.evaluation_scores,
                overall_score=request.evaluation_scores.get('overall_score', 0.0),
                judge_model=request.judge_model or "llama-70b"
            )
            db.add(evaluation)
            db.commit()

        return {"message": "Saved successfully", "version_id": version.id}
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=f"Database error: {str(e)}")

@app.get("/api/history")
def get_history(db: Session = Depends(get_db)):
    """
    Retrieves the history of saved prompt versions and their evaluations.
    """
    try:
        versions = db.query(models.PromptVersion).order_by(models.PromptVersion.created_at.desc()).limit(10).all()
        history = []
        for v in versions:
            eval_record = db.query(models.Evaluation).filter(models.Evaluation.prompt_version_id == v.id).first()
            history.append({
                "version_id": v.id,
                "prompt_id": v.prompt_id,
                "content": v.content,
                "model_used": v.model_used,
                "created_at": v.created_at,
                "evaluation_score": eval_record.scores.get("overall_score") if eval_record and eval_record.scores else None
            })
        return {"history": history}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Database error: {str(e)}")
