# Setup CORS
raw_origins = os.getenv("ALLOWED_ORIGINS", "http://localhost:5173,http://127.0.0.1:5173")
allowed_origins = [o.strip() for o in raw_origins.split(",") if o.strip()]

# allow_origin_regex covers Netlify's production domain AND every deploy-preview
# subdomain (e.g. agent-<hash>--promptchain-fyp.netlify.app) so a new preview URL
# never needs a manual CORS config update again — this exact class of bug already
# broke the deploy once tonight because ALLOWED_ORIGINS only had localhost in it.
app.add_middleware(
    CORSMiddleware,
    allow_origins=allowed_origins,
    allow_origin_regex=r"^(http://(localhost|127\.0\.0\.1):\d+|https://([a-zA-Z0-9-]+--)?promptchain-fyp\.netlify\.app)$",
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

class RunRequest(BaseModel):
    prompt: str = Field(..., description="The raw prompt from the editor")
    model: str = Field(..., description="The key of the model to run (e.g. 'llama-70b', 'nemotron-120b')")
    json_schema: Optional[Dict[str, Any]] = Field(None, description="Optional JSON Schema to enforce")

class EvaluateRequest(BaseModel):
    prompt: str = Field(..., description="The raw prompt used")
    output: str = Field(..., description="The output generated by the LLM")
    judge_model: str = Field("llama-8b", description="The key of the model to use as the judge")

class SaveRequest(BaseModel):
    title: str = "Untitled Prompt"
    prompt_content: str
    model_used: str
    json_schema: Optional[Dict[str, Any]] = None
    evaluation_scores: Optional[Dict[str, Any]] = None
    judge_model: Optional[str] = "llama-8b"

